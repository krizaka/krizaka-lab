/** The language of the page: `?lang=`, then the visitor's last choice, then the browser's. */
export function pickLocale(search: string, stored: string | null, browser: string | undefined): Locale {
  const asked = new URLSearchParams(search.replace(/^\?\/[^&]*&?/, "?")).get("lang");
  for (const l of [asked, stored, browser?.slice(0, 2)]) if (l === "en" || l === "fr") return l;
  return "en";
}
